use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let codec_dir = Path::new(&manifest_dir).join("src").join("codec");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");

    let mut modules: Vec<String> = Vec::new();
    if let Ok(entries) = fs::read_dir(&codec_dir) {
        for e in entries.flatten() {
            let path = e.path();
            if path.extension().map(|x| x == "rs").unwrap_or(false) {
                let stem = path.file_stem().unwrap().to_string_lossy().to_string();
                if stem == "mod" {
                    continue;
                }
                modules.push(stem);
            }
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
    // rerun if a new algorithm file appears
    println!("cargo:rerun-if-changed={}", codec_dir.display());

    modules.sort();
    let mut gen = String::new();
    gen.push_str("// AUTO-GENERATED by build.rs: do not edit.\n");
    gen.push_str("// Each file in src/codec/ (except mod.rs) is a module that must\n");
    gen.push_str("// export `pub const REGISTRY: &[RegistryEntry]`.\n\n");
    for m in &modules {
        let abs = codec_dir.join(format!("{m}.rs")).display().to_string();
        gen.push_str(&format!("#[path = \"{abs}\"] pub mod {m};\n"));
    }
    gen.push_str("\npub fn all_codecs_auto() -> Vec<crate::codec::CodecRegistration> {\n");
    gen.push_str("    let mut v: Vec<crate::codec::CodecRegistration> = Vec::new();\n");
    gen.push_str("    let entries: Vec<crate::codec::RegistryEntry> = [\n");
    for m in &modules {
        gen.push_str(&format!("        crate::codec::{m}::REGISTRY,\n"));
    }
    gen.push_str("    ].concat();\n");
    gen.push_str("    for e in entries {\n");
    gen.push_str("        v.push(crate::codec::CodecRegistration::base(\n");
    gen.push_str("            Box::new(crate::codec::DescribedCodec::new((e.make)(), e.description)),\n");
    gen.push_str("            e.group,\n");
    gen.push_str("        ));\n");
    gen.push_str("    }\n");
    gen.push_str("    v\n");
    gen.push_str("}\n");

    fs::write(Path::new(&out_dir).join("codec_autogen.rs"), gen).expect("write codec_autogen.rs");
}
