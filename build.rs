use std::env;
use std::fs;
use std::path::Path;

fn collect_rs(dir: &Path, base: &Path, out: &mut Vec<(String, String)>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for e in entries.flatten() {
            let path = e.path();
            if path.is_dir() {
                collect_rs(&path, base, out);
            } else if path.extension().map(|x| x == "rs").unwrap_or(false) {
                let stem = path.file_stem().unwrap().to_string_lossy().to_string();
                if stem == "mod" {
                    continue;
                }
                let rel = path.strip_prefix(base).unwrap();
                let rel_str = rel.display().to_string();
                // module name = sanitized relative path without extension, e.g.
                // "apex3d.rs" -> "apex3d", "many_attempt/apex3d.rs" -> "many_attempt_apex3d"
                let noext = rel.with_extension("").display().to_string();
                let name: String = noext
                    .chars()
                    .map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' })
                    .collect();
                out.push((name, rel_str));
            }
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let codec_dir = Path::new(&manifest_dir).join("src").join("codec");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");

    let mut files: Vec<(String, String)> = Vec::new();
    collect_rs(&codec_dir, &codec_dir, &mut files);
    files.sort();

    let mut gen = String::new();
    gen.push_str("// AUTO-GENERATED by build.rs: do not edit.\n");
    gen.push_str("// Each .rs file under src/codec/ (recursively, except mod.rs) must\n");
    gen.push_str("// export `pub const REGISTRY: &[RegistryEntry]`.\n\n");
    for (name, rel) in &files {
        let abs = codec_dir.join(rel).display().to_string();
        gen.push_str(&format!("#[path = \"{abs}\"] pub mod {name};\n"));
    }
    gen.push_str("\npub fn all_codecs_auto() -> Vec<crate::codec::CodecRegistration> {\n");
    gen.push_str("    let mut v: Vec<crate::codec::CodecRegistration> = Vec::new();\n");
    gen.push_str("    let entries: Vec<crate::codec::RegistryEntry> = [\n");
    for (name, _) in &files {
        gen.push_str(&format!("        crate::codec::{name}::REGISTRY,\n"));
    }
    gen.push_str("    ].concat();\n");
    gen.push_str("    for e in entries {\n");
    gen.push_str("        v.push(crate::codec::CodecRegistration::base(\n");
    gen.push_str("            Box::new(crate::codec::DescribedCodec::new((e.make)(), e.description)),\n");
    gen.push_str("            e.group,\n");
    gen.push_str("        ));\n");
    gen.push_str("    }\n");
    gen.push_str("    v\n");
    gen.push_str("}\n");

    fs::write(Path::new(&out_dir).join("codec_autogen.rs"), gen).expect("write codec_autogen.rs");
}
