use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::Path;

/// A single codec file with its module path (folder chain + file stem),
/// e.g. ["base", "layered"] for src/codec/base/layered.rs.
struct FileEntry {
    mod_path: Vec<String>,
    abs: String,
}

#[derive(Default)]
struct Dir {
    subdirs: BTreeMap<String, Dir>,
    files: Vec<FileEntry>,
}

fn sanitize(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

fn insert(node: &mut Dir, parts: &[String], abs: String) {
    if parts.len() == 1 {
        node.files.push(FileEntry {
            mod_path: parts.to_vec(),
            abs,
        });
    } else {
        let sub = node.subdirs.entry(parts[0].clone()).or_default();
        insert(sub, &parts[1..], abs);
    }
}

fn emit_module(dir: &Dir, indent: usize, out: &mut String) {
    let pad = " ".repeat(indent);
    for f in &dir.files {
        let name = f.mod_path.last().unwrap();
        out.push_str(&format!("{pad}#[path = \"{}\"] pub mod {name};\n", f.abs));
    }
    for (name, sub) in &dir.subdirs {
        out.push_str(&format!("{pad}pub mod {name} {{\n"));
        emit_module(sub, indent + 4, out);
        out.push_str(&format!("{pad}}}\n"));
    }
}

fn collect_rs(dir: &Path, base: &Path, out: &mut Vec<(Vec<String>, String)>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for e in entries.flatten() {
            let path = e.path();
            if path.is_dir() {
                collect_rs(&path, base, out);
            } else if path.extension().map(|x| x == "rs").unwrap_or(false) {
                let stem = path.file_stem().unwrap().to_string_lossy().to_string();
                if stem == "mod" {
                    continue;
                }
                let rel = path.strip_prefix(base).unwrap();
                let mut parts: Vec<String> = rel
                    .with_extension("")
                    .display()
                    .to_string()
                    .split('/')
                    .map(sanitize)
                    .collect();
                let abs = path.display().to_string();
                if let Some(last) = parts.last_mut() {
                    *last = sanitize(&stem);
                }
                out.push((parts, abs));
            }
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let codec_dir = Path::new(&manifest_dir).join("src").join("codec");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");

    // Watch the whole tree: new/removed codec files must trigger a rebuild
    // without requiring `cargo clean`.
    println!("cargo:rerun-if-changed={}", codec_dir.display());

    let mut files: Vec<(Vec<String>, String)> = Vec::new();
    collect_rs(&codec_dir, &codec_dir, &mut files);
    files.sort();

    // Build a tree mirroring the folder structure so that module paths match
    // file paths: src/codec/base/layered.rs -> codec::base::layered.
    let mut root = Dir::default();
    for (parts, abs) in &files {
        insert(&mut root, parts, abs.clone());
    }

    let mut gen = String::new();
    gen.push_str("// AUTO-GENERATED by build.rs: do not edit.\n");
    gen.push_str("// Each .rs file under src/codec/ (recursively, except mod.rs) must\n");
    gen.push_str("// export `pub const REGISTRY: &[RegistryEntry]`.\n\n");
    emit_module(&root, 0, &mut gen);
    gen.push_str("\npub fn all_codecs_auto() -> Vec<crate::codec::CodecRegistration> {\n");
    gen.push_str("    let mut v: Vec<crate::codec::CodecRegistration> = Vec::new();\n");
    gen.push_str("    let entries: Vec<crate::codec::RegistryEntry> = [\n");
    for (parts, _) in &files {
        let path = parts.join("::");
        gen.push_str(&format!("        crate::codec::{path}::REGISTRY,\n"));
    }
    gen.push_str("    ].concat();\n");
    gen.push_str("    for e in entries {\n");
    gen.push_str("        v.push(crate::codec::CodecRegistration::base(\n");
    gen.push_str("            (e.make)(),\n");
    gen.push_str("            e.group,\n");
    gen.push_str("            e.description,\n");
    gen.push_str("        ));\n");
    gen.push_str("    }\n");
    gen.push_str("    v\n");
    gen.push_str("}\n");

    fs::write(Path::new(&out_dir).join("codec_autogen.rs"), gen).expect("write codec_autogen.rs");
}
