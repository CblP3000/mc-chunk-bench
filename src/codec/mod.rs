//! Codec trait and registry of chunk storage algorithms.
//!
//! Directory layout (all subdirectories are scanned recursively by `build.rs`):
//!
//! - `base/` — reference/baseline algorithms (`raw`, `minecraft`, `rle`,
//!   `rle-linear`, `layered`); always kept in the benchmark.
//! - `custom/` — accepted custom codecs that earn their place in the benchmark.
//! - `disabled/` — codecs that are turned off (their `REGISTRY` is commented
//!   out) but kept for reference.
//! - `sandbox/` — **new** implementations for testing. Drop a file here,
//!   it is auto-registered (if it exports `REGISTRY`) and appears in the
//!   benchmark immediately. Promote it to `custom/` (or delete it) when done.
//!
//! New algorithms are **self-registering**: create a `.rs` file anywhere under
//! `src/codec/` exporting a `pub const REGISTRY: &[RegistryEntry]` and it is
//! picked up automatically by `build.rs` (no edits in this file are needed).

use crate::chunk::Chunk;
use crate::world::{BiomeRegistry, BlockRegistry};
use anyhow::Result;

pub struct Ctx<'a> {
    pub registry: &'a BlockRegistry,
    pub biomes: &'a BiomeRegistry,
    /// per biome-id: up to 255 global block ids (most common first)
    pub biome_block_lists: &'a [Vec<u32>],
}

pub trait Codec: Send + Sync {
    /// number of chunks encoded together in one call (1, or 4 for 32x32 tiles)
    fn group_size(&self) -> usize {
        1
    }

    fn encode_tile(&self, chunks: &[&Chunk], ctx: &Ctx) -> Vec<u8>;
    fn decode_tile(&self, bytes: &[u8], ctx: &Ctx) -> Result<Vec<Chunk>>;

    /// single-chunk convenience for group_size == 1 codecs
    fn encode(&self, chunk: &Chunk, ctx: &Ctx) -> Vec<u8> {
        self.encode_tile(&[chunk], ctx)
    }

    fn decode(&self, bytes: &[u8], ctx: &Ctx) -> Result<Chunk> {
        let mut v = self.decode_tile(bytes, ctx)?;
        if v.len() != 1 {
            anyhow::bail!("single-chunk decode expected 1 chunk, got {}", v.len());
        }
        Ok(v.remove(0))
    }
}

/// One entry of an algorithm's self-registration list. Declared inside the
/// algorithm's own file so that `src/codec/mod.rs` never has to change.
#[derive(Clone, Copy)]
pub struct RegistryEntry {
    /// short unique id used in reports, e.g. "my-algo"
    pub id: &'static str,
    /// human-readable name shown in reports and charts
    pub name: &'static str,
    /// method group used for coloring on charts: "raw" | "rle" | "minecraft" | "layered" | ...
    pub group: &'static str,
    pub description: &'static str,
    pub make: fn() -> Box<dyn Codec>,
}

/// A registered algorithm plus its metadata. Returned by the registry.
pub struct CodecRegistration {
    pub codec: Box<dyn Codec>,
    pub id: String,
    pub name: String,
    pub group: &'static str,
    pub description: String,
    /// true for entries created by the "compress everything with the same
    /// deflate" toggle
    pub gzip_extra: bool,
}

impl CodecRegistration {
    fn base(
        codec: Box<dyn Codec>,
        id: &'static str,
        name: &'static str,
        group: &'static str,
        description: &'static str,
    ) -> Self {
        Self {
            codec,
            id: id.to_string(),
            name: name.to_string(),
            group,
            description: description.to_string(),
            gzip_extra: false,
        }
    }
}

/// All registered algorithms with their groups.
/// If `with_gzip_extra` is set, every base method is additionally registered
/// wrapped with the same deflate (zlib, level 12) compressor.
pub fn all_registrations(with_gzip_extra: bool) -> Vec<CodecRegistration> {
    let bases = all_codecs_auto();
    if !with_gzip_extra {
        return bases;
    }
    let mut out = bases;
    for r in all_codecs_auto() {
        if r.id.contains("deflate") {
            continue;
        }
        let group = r.group;
        let level = flate2::Compression::new(12);
        let id = format!("{}+deflate{}", r.id, level.level());
        let name = format!("{}+deflate{} (zlib)", r.id, level.level());
        let description = format!(
            "Базовый метод «{}» + дополнительное сжатие deflate (zlib, level {}) \
             — одно и то же для всех методов.",
            r.id,
            level.level()
        );
        out.push(CodecRegistration {
            codec: Box::new(deflate::DeflateCodec::new(r.codec, level)),
            id,
            name,
            group,
            description,
            gzip_extra: true,
        });
    }
    out
}

/// Registry of all benchmarked algorithms (base set, no gzip extras).
pub fn all_codecs() -> Vec<Box<dyn Codec>> {
    all_codecs_auto().into_iter().map(|r| r.codec).collect()
}

